    print("=" * 88)
    headers = f"{'Configuration':<26} | {'Comp (%)':<14} | {'Lane Dev (m)':<14} | {'Coll (%)':<9} | {'Latency':<9} | {'FPS':<5}"
    print(headers)
    print("-" * 88)

