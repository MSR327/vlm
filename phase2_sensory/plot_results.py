def plot_termination_analysis(phase2_data, save_path):
    """
    Plots termination breakdown and lateral deviation distribution.
    """
    fig, axes = plt.subplots(1, 2, figsize=(11, 5))
    fig.suptitle("Phase 2 Safety & Termination Diagnostics", fontsize=13, fontweight='bold')

    # 1. Termination Modes Donut Chart
    ax1 = axes[0]
    term_counts = {}
    for term in phase2_data['terminations']:
        t_clean = term.replace('_', ' ').title()
        term_counts[t_clean] = term_counts.get(t_clean, 0) + 1

    labels = list(term_counts.keys())
    counts = [term_counts[k] for k in labels]
    palette = {'Completed': '#2ca02c', 'Collision': '#d62728', 'Out Of Lane': '#ff7f0e', 'Stall': '#9467bd'}
    colors = [palette.get(k, '#8c564b') for k in labels]

    wedges, texts, autotexts = ax1.pie(counts, labels=labels, autopct='%1.1f%%',
                                      startangle=140, colors=colors,
                                      wedgeprops=dict(width=0.45, edgecolor='w'))
    for autotext in autotexts:
        autotext.set_color('white')
        autotext.set_weight('bold')
    ax1.set_title("(a) Termination Reason Distribution")

    # 2. Lane Deviation Distribution Histogram + KDE
    ax2 = axes[1]
    devs = phase2_data['deviations']
    ax2.hist(devs, bins=10, density=True, alpha=0.6, color='#1f77b4', edgecolor='black')
    
    # Kernel fit
    mu = float(np.mean(devs))
    sigma = float(np.std(devs)) if np.std(devs) > 1e-4 else 0.05
    x = np.linspace(max(0, mu - 3 * sigma), mu + 3 * sigma, 100)
    y = (1.0 / (sigma * np.sqrt(2 * np.pi))) * np.exp(-0.5 * ((x - mu) / sigma)**2)
    ax2.plot(x, y, color='#d62728', linewidth=2.5, label=f'Gaussian Fit\n$\\mu={mu:.2f}m, \\sigma={sigma:.2f}m$')
    
    max_dev = getattr(C, 'MAX_CENTER_DEV', 3.0)
    ax2.axvline(max_dev, color='red', linestyle='--', linewidth=1.5, label=f'Threshold ({max_dev}m)')
    ax2.set_xlabel("Lane Center Deviation (m)", fontweight='bold')
    ax2.set_ylabel("Probability Density", fontweight='bold')
    ax2.set_title("(b) Lateral Tracking Precision Distribution")
    ax2.legend(loc='upper right')

    plt.tight_layout()
    plt.savefig(save_path)
    plt.close()
    print(f"[Plot] Saved termination analysis figure: {save_path}")


