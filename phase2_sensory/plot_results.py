    p2_d_std = float(np.std(phase2_data['deviations']))
    p2_coll = float(np.mean(phase2_data['collisions'])) * 100.0
    p2_r = float(np.mean(phase2_data['rewards']))
    p2_lat = float(np.mean(phase2_data['latencies']))
    p2_fps = 1000.0 / p2_lat if p2_lat > 0 else 0.0

    print("\n" + "=" * 88)
