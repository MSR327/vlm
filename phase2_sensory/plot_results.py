    models = list(PHASE1_BASELINES.keys()) + ['Phase 2 TransFuser-PPO']
    colors = ['#4c72b0', '#55a868', '#c44e52', '#8172b2', '#e28743']

    # 1. Route Completion (%)
    comp_means = [PHASE1_BASELINES[k]['completion'] for k in PHASE1_BASELINES] + [float(np.mean(phase2_data['completions']))]
    comp_stds = [PHASE1_BASELINES[k]['completion_std'] for k in PHASE1_BASELINES] + [float(np.std(phase2_data['completions']))]

    ax1 = axes[0, 0]
    bars1 = ax1.bar(range(len(models)), comp_means, yerr=comp_stds, capsize=4, color=colors, alpha=0.85, edgecolor='black', linewidth=1)
    ax1.set_ylabel("Route Completion (%)", fontweight='bold')
